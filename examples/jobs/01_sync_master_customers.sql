-- ========================================================
-- 顧客マスタの月初リセット（洗い替え型同期の前段）
-- ========================================================

-- 当月分の集計フィールドをリセットする対象がなければ正常終了
EXIT SUCCESS IF (
  SELECT COUNT(*) FROM LAPP_顧客マスタ WHERE 当月売上実績 > 0
) = 0, 'リセット対象の顧客がいないためスキップ';

UPDATE LAPP_顧客マスタ
SET 当月受注件数 = 0, 当月売上実績 = 0
WHERE 当月売上実績 > 0;
